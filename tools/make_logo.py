#!/usr/bin/env python3
"""Renders the Mara X Meter logo and writes it as a PROGMEM header for the boot and off screens.

The logo is a black and white bitmap (1 bit per pixel, most significant bit first, 1 = white, the format GxEPD2
uses). The firmware places it at a random position and slices it with random glitch bands, so only the static
artwork is generated here.

Usage:
    python3 tools/make_logo.py                       # writes lib/Display/LogoImage.h
    python3 tools/make_logo.py --png logo.png        # additionally saves a PNG to look at

Requires Pillow (pip install pillow) and the macOS system fonts DIN Condensed Bold and Impact; other TrueType
fonts can be passed with --font / --small-font.
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

WIDTH, HEIGHT = 336, 184  # the width must be a multiple of 8
FONT_BIG = "/System/Library/Fonts/Supplemental/DIN Condensed Bold.ttf"
FONT_SMALL = "/System/Library/Fonts/Supplemental/DIN Condensed Bold.ttf"
BLACK, WHITE = 0, 255


def text_image(text, font, fill):
    """Renders text tightly cropped on a transparent canvas."""
    left, top, right, bottom = font.getbbox(text)
    img = Image.new("L", (right - left + 2, bottom - top + 2), 255 - fill)
    ImageDraw.Draw(img).text((1 - left, 1 - top), text, font=font, fill=fill)
    return img


def render(font_big_path, font_small_path):
    img = Image.new("L", (WIDTH, HEIGHT), WHITE)
    draw = ImageDraw.Draw(img)

    # Word mark "MARA X", condensed and heavy, squeezed a little wider than the font draws it.
    big = ImageFont.truetype(font_big_path, 150)
    word = text_image("MARA X", big, BLACK)
    word = word.resize((WIDTH - 16, 104), Image.LANCZOS).point(lambda v: 255 if v > 128 else 0)
    wx, wy = 8, 4
    img.paste(word, (wx, wy))

    # A diagonal cut through the word mark; the part below it is shifted, the classic slice.
    cut_y = wy + 60
    cut_x0, cut_x1 = wx + 40, wx + word.width - 60
    lower = img.crop((0, 0, WIDTH, HEIGHT)).copy()
    mask = Image.new("L", (WIDTH, HEIGHT), 0)
    ImageDraw.Draw(mask).polygon([(0, cut_y + 10), (cut_x0, cut_y + 10), (cut_x1, cut_y - 8), (WIDTH, cut_y - 8),
                                  (WIDTH, HEIGHT), (0, HEIGHT)], fill=255)
    shifted = Image.new("L", (WIDTH, HEIGHT), WHITE)
    shifted.paste(lower, (6, 0))
    img.paste(shifted, (0, 0), mask)
    # White gap along the cut so the two halves read as separate pieces.
    draw.line([(0, cut_y + 10), (cut_x0, cut_y + 10), (cut_x1, cut_y - 8), (WIDTH, cut_y - 8)], fill=WHITE, width=3)

    # Bar with "METER" knocked out, chamfered right end, a title plate.
    bar_y0, bar_y1 = 118, 162
    bar_x0, bar_x1 = 8, 262
    draw.polygon([(bar_x0, bar_y0), (bar_x1, bar_y0), (bar_x1 - 18, bar_y1), (bar_x0, bar_y1)], fill=BLACK)
    small = ImageFont.truetype(font_small_path, 64)
    meter = text_image("METER", small, WHITE)
    meter = meter.resize((int(meter.width * 1.25), 34), Image.LANCZOS).point(lambda v: 255 if v > 128 else 0)
    inv = Image.eval(meter, lambda v: 255 - v)  # mask: text pixels opaque
    img.paste(WHITE, (bar_x0 + 10, bar_y0 + 5), inv)
    # Hazard stripes after the bar.
    for i in range(5):
        x = bar_x1 + 4 + i * 14
        draw.polygon([(x + 8, bar_y0), (x + 14, bar_y0), (x + 14 - 18, bar_y1), (x + 8 - 18, bar_y1)], fill=BLACK)
    # Small tag line right of the stripes area, like a version plate.
    tag = ImageFont.truetype(font_small_path, 26)
    t = text_image("HX // STEAM // SHOT", tag, BLACK).point(lambda v: 255 if v > 128 else 0)
    img.paste(t, (bar_x0 + 2, bar_y1 + 2))

    return img.point(lambda v: 255 if v > 128 else 0)


def to_header(img, name):
    data = list(img.get_flattened_data()) if hasattr(img, 'get_flattened_data') else list(img.getdata())
    out = bytearray()
    for y in range(HEIGHT):
        for x in range(0, WIDTH, 8):
            byte = 0
            for bit in range(8):
                if data[y * WIDTH + x + bit]:
                    byte |= 0x80 >> bit
            out.append(byte)
    lines = [
        "// Generated by tools/make_logo.py, do not edit by hand.",
        "#pragma once",
        "#include <stdint.h>",
        "#if defined(ESP8266) || defined(ESP32)",
        "#include <pgmspace.h>",
        "#elif !defined(PROGMEM)",
        "#define PROGMEM",
        "#endif",
        "",
        f"constexpr int16_t k{name}Width = {WIDTH};",
        f"constexpr int16_t k{name}Height = {HEIGHT};",
        f"// 1 bit per pixel, most significant bit first, 1 = white.",
        f"const unsigned char k{name}[] PROGMEM = {{",
    ]
    for i in range(0, len(out), 16):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in out[i : i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--out", default="lib/Display/LogoImage.h")
    parser.add_argument("--png", help="also save the picture as PNG")
    parser.add_argument("--font", default=FONT_BIG)
    parser.add_argument("--small-font", default=FONT_SMALL)
    args = parser.parse_args()
    img = render(args.font, args.small_font)
    if args.png:
        img.resize((WIDTH * 2, HEIGHT * 2), Image.NEAREST).save(args.png)
    Path(args.out).write_text(to_header(img, "Logo"))
    print(f"wrote {args.out} ({WIDTH}x{HEIGHT}, {WIDTH * HEIGHT // 8} bytes)")


if __name__ == "__main__":
    main()
